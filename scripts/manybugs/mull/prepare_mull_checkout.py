#!/usr/bin/env python3
"""Fase 1 of the mull baseline pipeline (see mull_baseline_plan.md).

Given a ManyBugs subject_id (e.g. "gzip-2009-08-16-3fe0caeada-39a362ae9d"),
this script:

  1. builds (or reuses) a reproducible mull toolchain image from
     scripts/manybugs/mull/Dockerfile.<project>
  2. extracts /experiment from the prosyslab/manybugs:<scenario> image
     (same mechanism ManyBugsAdapter.checkout_subject uses)
  3. copies that source into a fresh container from the toolchain image
  4. builds it with clang-9 + the mull-ir-frontend-9 pass plugin, using the
     flags baked into the Dockerfile (MULL_CFLAGS/MULL_LDFLAGS), passed to
     `make` as command-line arguments (NOT only as environment variables —
     see "Achado de engenharia" in mull_baseline_plan.md: a Makefile
     generated by `./configure CFLAGS=...` freezes its own CFLAGS, which
     wins over an inherited env var of the same name)
  5. sanity-checks that the resulting binary actually contains embedded
     mutations (a `.mull_mutants` ELF section) before declaring success —
     this is not cosmetic: an unnoticed silent instrumentation failure was
     the exact failure mode of the -O1/-fexperimental-new-pass-manager and
     CFLAGS gotchas documented in the plan.

Does NOT run any tests or mull-runner — that's run_mull_subject.py
(Fase 2). This script only produces a qualified, instrumented build and
leaves the container running so Fase 2 can exec into it.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from dataclasses import dataclass, asdict
from datetime import datetime
from pathlib import Path

import docker

MULL_DIR = Path(__file__).resolve().parent
IMAGE_REGISTRY = "prosyslab/manybugs"
PLATFORM = "linux/amd64"
TOOLCHAIN_IMAGE_PREFIX = "manybugs-mull"
CONTAINER_SOURCE_DIR = "/experiment"


def ts() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def log(msg: str) -> None:
    print(f"[{ts()}] {msg}", flush=True)


def _docker_client() -> docker.DockerClient:
    return docker.from_env()


def _project_from_subject_id(subject_id: str) -> str:
    # subject_id format: "<project>-<...scenario details...>"
    return subject_id.split("-", 1)[0]


@dataclass
class MullCheckout:
    subject_id: str
    project: str
    scenario_image: str
    toolchain_image: str
    container_id: str
    source_dir: str
    build_ok: bool
    build_log_tail: str
    mutants_embedded: bool
    binary_path: str


def _run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, **kwargs)


def build_toolchain_image(project: str, *, force_rebuild: bool = False) -> str:
    """Build (or reuse) the mull toolchain image for *project*.

    Tag is content-addressed by the Dockerfile path only (not hashed) —
    docker build's own layer cache makes repeat builds cheap; --force
    triggers a real rebuild (e.g. after editing the Dockerfile).
    """
    dockerfile = MULL_DIR / f"Dockerfile.{project}"
    if not dockerfile.exists():
        raise FileNotFoundError(
            f"No mull Dockerfile for project '{project}' at {dockerfile}. "
            f"Each family needs its own Dockerfile.<project> — see "
            f"mull_baseline_plan.md Fase 1 (re-verify glibc/arch per family, "
            f"don't assume the gzip recipe applies)."
        )
    tag = f"{TOOLCHAIN_IMAGE_PREFIX}:{project}"

    client = _docker_client()
    if not force_rebuild:
        try:
            client.images.get(tag)
            log(f"[toolchain] reusing cached image {tag}")
            return tag
        except docker.errors.ImageNotFound:
            pass

    log(f"[toolchain] building {tag} from {dockerfile}")
    result = _run(
        ["docker", "build", "--platform", PLATFORM, "-t", tag, "-f", str(dockerfile), str(MULL_DIR)]
    )
    if result.returncode != 0:
        raise RuntimeError(f"docker build failed for {tag}:\n{result.stdout}\n{result.stderr}")
    return tag


def extract_scenario_source(subject_id: str, dest_dir: Path) -> str:
    """Extract /experiment from prosyslab/manybugs:<subject_id> into dest_dir.

    Mirrors ManyBugsAdapter.checkout_subject's docker cp mechanism.
    """
    image_name = f"{IMAGE_REGISTRY}:{subject_id}"
    client = _docker_client()

    log(f"[checkout] pulling {image_name}")
    try:
        client.images.pull(image_name, platform=PLATFORM)
    except TypeError:
        client.images.pull(image_name)

    log(f"[checkout] extracting /experiment from {image_name}")
    try:
        container = client.containers.create(image_name, platform=PLATFORM)
    except TypeError:
        container = client.containers.create(image_name)
    try:
        dest_dir.mkdir(parents=True, exist_ok=True)
        result = _run(["docker", "cp", f"{container.id}:/experiment", str(dest_dir / "experiment")])
        if result.returncode != 0:
            raise RuntimeError(f"docker cp out failed: {result.stderr}")
    finally:
        container.remove(force=True)

    return image_name


def build_instrumented_binary(
    toolchain_image: str,
    host_source_dir: Path,
    *,
    binary_relpath: str = "gzip",
    make_jobs: int = 2,
    cflags_at_configure_time: bool = False,
    post_configure_patch: str | None = None,
) -> MullCheckout:
    """Start a container from *toolchain_image*, copy the extracted source
    in, and build it with the mull-instrumented flags baked into the image.

    cflags_at_configure_time: some projects (libtiff) trigger on-demand
    recompilation during the test run itself (test scripts run bare `make
    <target>`, no CFLAGS override) — for those, the mull flags must be
    frozen into the Makefile by `./configure CFLAGS=...`, or that later
    ad-hoc compile silently reverts to un-instrumented default flags (and,
    for libtiff specifically, a bitness mismatch against the already-built
    -m32 library). For projects with a single monolithic test binary
    (gzip) this must stay False — there, baking CFLAGS into configure is
    what caused the CFLAGS-precedence gotcha in the first place (see
    "Achado de engenharia" in mull_baseline_plan.md). Not safe to assume
    either way for an untested project.

    post_configure_patch: optional shell command run (via `bash -lc`,
    cwd=src_dir) after ./configure and before `make` — for source-tree
    patches that a fresh `./configure` run would otherwise clobber (e.g.
    libtiff's test/Makefile has an unresolved Automake conditional that
    needs a one-line sed fix after every configure).
    """
    client = _docker_client()
    try:
        container = client.containers.create(
            toolchain_image, platform=PLATFORM, command="sleep infinity", detach=True
        )
    except TypeError:
        container = client.containers.create(toolchain_image, command="sleep infinity", detach=True)
    container.start()

    try:
        result = _run(
            ["docker", "cp", str(host_source_dir / "experiment"), f"{container.id}:/"]
        )
        if result.returncode != 0:
            raise RuntimeError(f"docker cp in failed: {result.stderr}")

        src_dir = f"{CONTAINER_SOURCE_DIR}/src"

        if cflags_at_configure_time:
            log("[build] configure (CC=clang-9, mull CFLAGS/LDFLAGS baked in at "
                "configure time — this project recompiles on demand during tests)")
            configure_cmd = (
                f'cd {src_dir} && ./configure CC=clang-9 CFLAGS="$MULL_CFLAGS" LDFLAGS="$MULL_LDFLAGS"'
            )
        else:
            log("[build] configure (CC=clang-9, no CFLAGS at configure time — "
                "flags are supplied to `make` below as command-line args)")
            configure_cmd = f"cd {src_dir} && ./configure CC=clang-9"
        cfg = _exec(container, ["bash", "-lc", configure_cmd])

        if post_configure_patch:
            log(f"[build] applying post-configure patch: {post_configure_patch}")
            patch = _exec(container, ["bash", "-lc", f"cd {src_dir} && {post_configure_patch}"])
            if patch["exit_code"] != 0:
                log(f"[build] WARNING: post-configure patch failed: {patch['output'][-500:]}")

        log(f"[build] make -j{make_jobs} with mull-instrumented CFLAGS/LDFLAGS "
            "(passed as make arguments, not env vars)")
        build_cmd = (
            f"cd {src_dir} && make -j{make_jobs} CC=clang-9 "
            f'CFLAGS="$MULL_CFLAGS" LDFLAGS="$MULL_LDFLAGS"'
        )
        build = _exec(container, ["bash", "-lc", build_cmd])
        build_ok = build["exit_code"] == 0
        tail = "\n".join(build["output"].splitlines()[-15:])

        binary_path = f"{src_dir}/{binary_relpath}"
        mutants_embedded = False
        if build_ok:
            check = _exec(
                container,
                ["bash", "-lc", f"readelf -S {binary_path} 2>/dev/null | grep -q mull_mutants"],
            )
            mutants_embedded = check["exit_code"] == 0
            if not mutants_embedded:
                log(
                    "[build] WARNING: build succeeded but no .mull_mutants section found — "
                    "this is the exact silent-failure mode documented in the plan "
                    "(-O1/-fexperimental-new-pass-manager or CFLAGS precedence). "
                    "Do not proceed to Fase 2 with this checkout."
                )

        return MullCheckout(
            subject_id="",  # filled by caller
            project="",  # filled by caller
            scenario_image="",  # filled by caller
            toolchain_image=toolchain_image,
            container_id=container.id,
            source_dir=src_dir,
            build_ok=build_ok,
            build_log_tail=tail,
            mutants_embedded=mutants_embedded,
            binary_path=binary_path,
        )
    except Exception:
        container.remove(force=True)
        raise


def _exec(container, cmd: list[str]) -> dict:
    result = subprocess.run(
        ["docker", "exec", container.id, *cmd],
        capture_output=True,
        text=True,
    )
    return {
        "exit_code": result.returncode,
        "output": result.stdout + result.stderr,
    }


# Default built binary path, relative to <container_source_dir>/src (i.e.
# where ./configure was run) — NOT relative to the repo root. Only the
# projects actually investigated have an entry — anything else must pass
# --binary-relpath explicitly rather than silently guessing.
DEFAULT_BINARY_RELPATH = {
    "gzip": "gzip",
    "lighttpd": "lighttpd",
    "libtiff": "tools/tiffcp",
}

# Projects where test scripts trigger on-demand recompilation (bare `make
# <target>`, no CFLAGS override) during the test run itself — for these,
# mull's CFLAGS must be frozen into the Makefile via `./configure
# CFLAGS=...`, not just passed to the initial `make`. See
# build_instrumented_binary()'s cflags_at_configure_time docstring.
CFLAGS_AT_CONFIGURE_TIME = {"libtiff"}

# Shell command to run after ./configure, before make — for source patches
# that a fresh ./configure run would otherwise clobber by regenerating the
# file. libtiff's test/Makefile has an unresolved Automake conditional
# (`@am__EXEEXT_TRUE@` never substituted, "missing separator" make error)
# — root cause not chased further (autoreconf -fi fails on an unrelated
# AC_CONFIG_MACRO_DIRS/ACLOCAL_AMFLAGS conflict; this checkout is 2005-era,
# too old for a clean regenerate with modern autotools). Not needed by the
# explicit .sh.log targets the test suite actually invokes, so a surgical
# sed is safe.
POST_CONFIGURE_PATCH = {
    "libtiff": "sed -i 's/^@am__EXEEXT_TRUE@//' test/Makefile",
}

# Parallel `make -jN` jobs, per project. Default 2 (validated safe for
# gzip). lighttpd's recursive Autotools/libtool build has a confirmed
# race at -j2 that silently drops the mull-ir-frontend instrumentation
# from the final linked binary (individual .o files get it fine — the
# final `lighttpd` executable sometimes doesn't; not reliably every
# time, which is what makes it a race and not a deterministic flag bug
# like the gzip CFLAGS-precedence one). -j1 was confirmed to build
# deterministically with .mull_mutants present in the final binary. Not
# root-caused further (which specific recursive target races) — -j1 is
# slower but correct, and was not worth chasing down for a build that
# takes ~2-3 minutes either way.
DEFAULT_MAKE_JOBS = {
    "gzip": 2,
    "lighttpd": 1,
}


def prepare_mull_checkout(
    subject_id: str,
    *,
    project: str | None = None,
    workdir: Path | None = None,
    force_rebuild_toolchain: bool = False,
    binary_relpath: str | None = None,
    make_jobs: int | None = None,
) -> MullCheckout:
    project = project or _project_from_subject_id(subject_id)
    workdir = workdir or Path(f".mull_checkout_{subject_id}")
    if binary_relpath is None:
        binary_relpath = DEFAULT_BINARY_RELPATH.get(project)
        if binary_relpath is None:
            raise ValueError(
                f"No default binary path for project '{project}' — pass --binary-relpath explicitly."
            )
    if make_jobs is None:
        make_jobs = DEFAULT_MAKE_JOBS.get(project, 2)

    toolchain_image = build_toolchain_image(project, force_rebuild=force_rebuild_toolchain)
    scenario_image = extract_scenario_source(subject_id, workdir)
    checkout = build_instrumented_binary(
        toolchain_image,
        workdir,
        binary_relpath=binary_relpath,
        make_jobs=make_jobs,
        cflags_at_configure_time=project in CFLAGS_AT_CONFIGURE_TIME,
        post_configure_patch=POST_CONFIGURE_PATCH.get(project),
    )
    checkout.subject_id = subject_id
    checkout.project = project
    checkout.scenario_image = scenario_image
    return checkout


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--subject-id", required=True, help="e.g. gzip-2009-08-16-3fe0caeada-39a362ae9d")
    parser.add_argument("--project", help="Defaults to the prefix of --subject-id (e.g. 'gzip')")
    parser.add_argument("--workdir", help="Host dir to extract source into (default: .mull_checkout_<subject_id>)")
    parser.add_argument("--force-rebuild-toolchain", action="store_true")
    parser.add_argument("--binary-relpath", help="e.g. src/lighttpd — required if --project has no default")
    parser.add_argument("--make-jobs", type=int, help="Overrides the per-project default (gzip=2, lighttpd=1)")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    checkout = prepare_mull_checkout(
        args.subject_id,
        project=args.project,
        workdir=Path(args.workdir) if args.workdir else None,
        force_rebuild_toolchain=args.force_rebuild_toolchain,
        binary_relpath=args.binary_relpath,
        make_jobs=args.make_jobs,
    )
    print(json.dumps(asdict(checkout), indent=2))
    if not checkout.build_ok or not checkout.mutants_embedded:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
